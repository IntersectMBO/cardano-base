-- | Poseidon instance parameters and constants.
--
-- This module holds the /data/ of each registered Poseidon instance — round
-- counts, width, partial-round S-box lane, MDS matrix and round constants —
-- together with the variant registry that a future Plutus builtin
-- (@bls12_381_poseidonPermutation@, per the CIP /Poseidon Permutation
-- Built-in for Plutus/) uses to select a parameter set by 'Integer' index.
-- The binding logic lives in "Cardano.Crypto.Poseidon.Internal", which
-- documents the full contract of the underlying C permutation.
--
-- == Provenance
--
-- Both registered instances are over the BLS12-381 scalar field and carry
-- the values of the machine-readable constants files shipped with the CIP,
-- cross-validated there against the upstream implementations
-- (@check-constants.py@ re-derives every vector):
--
-- * 'midnightWidth3' (registry index 0): the instance behind
--   <https://github.com/midnightntwrk/midnight-zk midnight-zk>'s Poseidon
--   chip — width 3, @R_F = 8@, @R_P = 60@, S-box @x^5@, partial-round S-box
--   on the __last__ lane. Constants generated with
--   @generate_parameters_grain.sage 1 0 255 3 8 60 \<r\>@ (the
--   pasta-hadeshash generator); source of truth
--   @circuits\/src\/hash\/poseidon\/constants\/blstrs.rs@ upstream,
--   converted to decimal integers in the CIP's
--   @midnight-poseidon-constants.json@.
--
-- * 'circomWidth3' (registry index 1): the width-3 instance of the
--   <https://github.com/jmagan/poseidon-bls12381-circom circom BLS12-381 port>
--   (following the framing of the widely used circomlib library) — width 3,
--   @R_F = 8@, @R_P = 56@, S-box @x^5@, partial-round S-box on the
--   __first__ lane. Constants generated with
--   @generate_params_poseidon.sage 1 0 255 3 5 128 \<r\>@ (the hadeshash
--   generator); source of truth @circuits\/poseidon255_constants.circom@
--   upstream, shipped in the CIP's @circom-bls-t3-poseidon-constants.json@.
--   The values here are the upstream (first-lane) form; the C core
--   hard-codes the S-box on the last lane, so the binding realizes this
--   instance through the exact state-reversal conjugation
--   ('conjugateInstance') — observationally identical, hence not a distinct
--   variant under the registry contract.
--
-- All lists are order-sensitive: the permutation consumes round constants
-- strictly sequentially and reads the MDS matrix row-major, so any
-- reordering produces wrong digests, not errors.
--
-- == Tested properties
--
-- The test suite (@Test.Crypto.Poseidon@) asserts, beyond the count
-- invariants, the CIP's admission criteria for each registered instance:
-- all values are canonical field elements (@0 <= x < r@ for the BLS12-381
-- scalar field order @r@); the ARK constants are pairwise distinct and
-- nonzero; the matrix is genuinely MDS (every square minor nonzero,
-- [GKRRS21] footnote 7); no infinitely long subspace trail keeps the
-- partial-round S-box inactive — the only @M@-invariant subspace contained
-- in @{x : x_sboxlane = 0}@ is the trivial one, checked as full rank of the
-- matrix with rows @e_l M^j@, @j = 0 .. t-1@ ([GKRRS21] section 2.3;
-- [GRS20, eprint 2020\/500]); and a pinned SHA256 digest freezes the exact
-- values and order. (The stronger condition that no power @M^i@ has /any/
-- eigenvalue in @F_r@ is sufficient but __not__ necessary — both registered
-- width-3 instances have such eigenvalues yet satisfy the criterion above,
-- which is why the CIP relaxes the check to the subspace-trail criterion.)
--
-- [GKRRS21]: Grassi, Khovratovich, Rechberger, Roy, Schofnegger,
-- \"Poseidon: A New Hash Function for Zero-Knowledge Proof Systems\",
-- USENIX Security 2021, <https://eprint.iacr.org/2019/458>.
--
-- [GRS20]: Grassi, Rechberger, Schofnegger, \"Proving Resistance Against
-- Infinitely Long Subspace Trails: How to Choose the Linear Layer\",
-- <https://eprint.iacr.org/2020/500>.
module Cardano.Crypto.Poseidon.Constants (
  PoseidonInstance (..),
  PartialSBoxLane (..),
  batchSize,
  conjugateInstance,
  midnightWidth3,
  circomWidth3,
  poseidonVariants,
) where

-- | Which state element the partial rounds apply the S-box to. This is a
-- structural choice the Poseidon paper leaves open and implementations in
-- the wild resolve differently; it is /not/ cosmetic — the same numeric
-- constants produce entirely different permutations under the two choices.
-- The C core hard-codes 'SBoxLast'; an 'SBoxFirst' instance is realized
-- through 'conjugateInstance' (see there).
data PartialSBoxLane
  = -- | S-box on the first state element (the circom\/circomlib lineage).
    SBoxFirst
  | -- | S-box on the last state element (midnight-zk, the C core, and the
    -- reference implementation in the test suite).
    SBoxLast
  deriving (Eq, Show)

-- | The parameters and constants of one Poseidon instance over the
-- BLS12-381 scalar field, in the (upstream) form of its CIP constants file.
--
-- Only data lives here; derived quantities are functions ('batchSize',
-- 'conjugateInstance') so they cannot drift out of sync with the fields
-- they are computed from.
data PoseidonInstance = PoseidonInstance
  { nbFullRounds :: !Int
  -- ^ @R_F@, the number of full rounds (S-box on every state element).
  -- Must be even: the permutation runs @R_F \`div\` 2@ full rounds before
  -- and after the partial rounds.
  , nbPartialRounds :: !Int
  -- ^ @R_P@, the number of partial rounds (S-box on the 'partialSBoxLane'
  -- element only).
  , width :: !Int
  -- ^ The state width @w@ (capacity + rate elements).
  , partialSBoxLane :: !PartialSBoxLane
  -- ^ The state element the partial rounds apply the S-box to — the lane
  -- the 'mds' and 'ark' values below are /for/. The template constructor
  -- in "Cardano.Crypto.Poseidon.Internal" normalizes an 'SBoxFirst'
  -- instance to the C-native last-lane form via 'conjugateInstance'.
  , mds :: ![[Integer]]
  -- ^ The @w × w@ MDS matrix as a list of rows, mirroring the row-major
  -- orientation declared in the CIP constants file
  -- (@state'_i = sum_j M_ij * state_j@) so the two can be compared
  -- directly. The C buffer wants it flattened row-major; that flattening
  -- happens in exactly one place, the context constructor in
  -- "Cardano.Crypto.Poseidon.Internal". Order is load-bearing.
  , ark :: ![Integer]
  -- ^ The raw (uncomposed) add-round-key constants,
  -- @(R_F + R_P) * w@ of them, in consumption order. Order is
  -- load-bearing. The @w@ trailing zero constants required by the C
  -- permutation (see "Cardano.Crypto.Poseidon.Internal", /Zero padding/)
  -- are __not__ part of this list; the context constructor provides them
  -- via zero-initialized allocation.
  }
  deriving (Eq, Show)

-- | The @batch_size@ to configure the C permutation with: @R_P + 1@.
--
-- This is a function of the instance rather than a stored field so it
-- cannot disagree with 'nbPartialRounds'. The value @R_P + 1@ makes
-- @R_P \`div\` batch_size == 0@, i.e. it disables the batched partial-round
-- optimization entirely. That is deliberate: batched partial rounds consume
-- /composed/ constants derived from the MDS and ARK — feeding them the raw
-- 'ark' list produces garbage digests and out-of-bounds reads. See
-- "Cardano.Crypto.Poseidon.Internal", /Batched partial rounds/, for the full
-- story and the future optimization path.
batchSize :: PoseidonInstance -> Int
batchSize inst = nbPartialRounds inst + 1

-- | The exact state-reversal conjugation of an instance: the observationally
-- identical instance with the state read in the opposite lane order.
--
-- Per the CIP (/Parameters/): @M'_ij = M_(t-1-i)(t-1-j)@ (row and column
-- order reversed), each round's @w@-element ARK chunk reversed, and the
-- S-box lane mirrored (first ↔ last). Running the conjugated instance on
-- the /reversed/ input state and reversing the output state computes
-- exactly the original instance's permutation — which is how the binding
-- realizes an 'SBoxFirst' instance on the C core's hard-coded last-lane
-- S-box (see "Cardano.Crypto.Poseidon.Internal", /Lane normalization/).
-- For the circom instance the result equals the @conjugated_form@ shipped
-- in its CIP constants file.
--
-- The conjugation is an involution: applying it twice gives back the
-- original instance (asserted in the test suite).
conjugateInstance :: PoseidonInstance -> PoseidonInstance
conjugateInstance inst =
  inst
    { partialSBoxLane = case partialSBoxLane inst of
        SBoxFirst -> SBoxLast
        SBoxLast -> SBoxFirst
    , mds = reverse (map reverse (mds inst))
    , ark = concatMap reverse (chunksOf (width inst) (ark inst))
    }
  where
    chunksOf _ [] = []
    chunksOf n xs = let (c, rest) = splitAt n xs in c : chunksOf n rest

-- | Look up a Poseidon variant by registry index.
--
-- This registry backs a future Plutus builtin that selects a parameter set
-- by an 'Integer' index; it mirrors the instance registry of the CIP
-- /Poseidon Permutation Built-in for Plutus/ and must stay aligned with it.
-- The registry contract:
--
-- * indices are __append-only__: new instances can be added, none can ever
--   be removed;
-- * the meaning of an index, once assigned, is __never changed or reused__
--   — on-chain scripts depend on it;
-- * a faster but observably identical implementation of an existing index
--   (e.g. the batched-constants optimization, or the conjugated realization
--   of index 1) is __not__ a new variant;
-- * an index identifies a __permutation, never a hash__: framings (capacity
--   tags, absorption order, digest lanes) are not part of an entry, and
--   operating an existing index with a different framing never requires a
--   new index.
--
-- Registered variants:
--
-- +-------+------------------------------------------------------------+
-- | Index | Instance                                                   |
-- +=======+============================================================+
-- | 0     | 'midnightWidth3' (midnight-zk; @R_P = 60@, S-box lane last)|
-- +-------+------------------------------------------------------------+
-- | 1     | 'circomWidth3' (circom BLS12-381 port; @R_P = 56@, S-box   |
-- |       | lane first)                                                |
-- +-------+------------------------------------------------------------+
poseidonVariants :: Integer -> Maybe PoseidonInstance
poseidonVariants 0 = Just midnightWidth3
poseidonVariants 1 = Just circomWidth3
poseidonVariants _ = Nothing

